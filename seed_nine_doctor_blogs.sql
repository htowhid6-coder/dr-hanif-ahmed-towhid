<ul>
  <li><strong>ইস্কেমিক স্ট্রোক (Ischemic Stroke):</strong> মস্তিষ্কের কোনো প্রধান বা শাখা রক্তনালীর ভেতরে রক্ত জমাট বেঁধে (Blood Clot/Thrombus) রক্তপ্রবাহ সম্পূর্ণরূপে বন্ধ হয়ে গেলে এটি ঘটে। বিশ্বের এবং আমাদের দেশের প্রায় ৮৫ শতাংশ স্ট্রোকই এই ধরনের।</li>
  <li><strong>হেমোরেজিক স্ট্রোক (Hemorrhagic Stroke):</strong> অনিয়ন্ত্রিত উচ্চ রক্তচাপের কারণে মস্তিষ্কের কোনো সূক্ষ্ম সর্পিল রক্তনালী ফেটে গিয়ে ভেতরে রক্তক্ষরণ হলে এটি ঘটে। এটি অত্যন্ত মারাত্মক ও দ্রুত প্রাণঘাতী হতে পারে।</li>
</ul>

<p>এছাড়া আরেকটি মারাত্মক সতর্কবার্তা রয়েছে যাকে বলা হয় <strong>টিআইএ (Transient Ischemic Attack বা Mini-Stroke)</strong>। এতে স্ট্রোকের লক্ষণগুলো কয়েক মিনিট বা ঘণ্টার জন্য দেখা দিয়ে আবার একা একাই সেরে যায়। অনেকেই ভাবেন রোগ ভালো হয়ে গেছে। অথচ এটি হলো আসন্ন বড় ও মারাত্মক স্ট্রোকের আগাম বিপদসংকেত!</p>

<h2>বিশ্বজনীন "FAST" নিয়ম: সাধারণ মানুষ যেভাবে ১ মিনিটে স্ট্রোক চিনবেন</h2>
<p>স্ট্রোক শনাক্ত করার জন্য কোনো বিশেষজ্ঞ ডাক্তার হওয়ার প্রয়োজন নেই। আপনি সাধারণ যে কেউই মাত্র ১ মিনিটের মধ্যে <strong>FAST</strong> ফর্মুলা ব্যবহার করে ঘরে বসেই নিশ্চিত হতে পারেন:</p>

<ol>
  <li><strong>F - Face Drooping (মুখের বিকৃতি):</strong> রোগীকে বলুন একগাল হেসে দাঁত দেখাতে। লক্ষ্য করুন মুখের একপাশ কি বাঁকা হয়ে ঝুলে পড়ছে? হাসির সময় কি মুখের এক কোণা নিচে নেমে যাচ্ছে?</li>
  <li><strong>A - Arm Weakness (হাতে দুর্বলতা):</strong> রোগীকে বলুন দুই হাত একসাথে সামনের দিকে সোজা করে ১০ সেকেন্ড তুলে ধরে রাখতে। লক্ষ্য করুন একটি হাত কি দুর্বল হয়ে নিজে নিজেই নিচে পড়ে যাচ্ছে বা তিনি কি একটি হাত তুলতে পারছেন না?</li>
  <li><strong>S - Speech Difficulty (কথায় জড়তা):</strong> রোগীকে একটি সহজ বাক্য বলতে বলুন—যেমন: "আজকের আবহাওয়া খুব সুন্দর।" তিনি কি কথাটি পরিষ্কারভাবে বলতে পারছেন, নাকি কথা জড়িয়ে যাচ্ছে, তোতলামি হচ্ছে, কিংবা তিনি কথা একদমই বলতে পারছেন না?</li>
  <li><strong>T - Time to Call Emergency (জরুরি হাসপাতালে নেওয়ার সময়):</strong> উপরের তিনটি লক্ষণের যেকোনো একটিও যদি চোখে পড়ে, তবে এক সেকেন্ডও ঘরে বসে থাকবেন না। ঘড়ি দেখুন এবং সাথে সাথে রোগীকে সিটি স্ক্যান (CT Scan) সুবিধাযুক্ত বড় হাসপাতালের জরুরি বিভাগে নিয়ে যান!</li>
