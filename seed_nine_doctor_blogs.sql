<h2>সাড়ে চার ঘণ্টার জাদুকরী গোল্ডেন উইন্ডো</h2>
<p>ইস্কেমিক স্ট্রোকের ক্ষেত্রে আধুনিক চিকিৎসাবিজ্ঞানের সবচেয়ে বড় আশির্বাদ হলো—লক্ষণ শুরু হওয়ার প্রথম <strong>সাড়ে চার ঘণ্টা (4.5 Hours)</strong>। এই সময়ের মধ্যে রোগীকে হাসপাতালে পৌঁছাতে পারলে এবং সিটি স্ক্যানে রক্তক্ষরণ না থাকলে, চিকিৎসকরা একটি বিশেষ ইনজেকশন দিতে পারেন যাকে বলা হয় <strong>আইভি থ্রম্বোলাইসিস (IV Thrombolysis / rtPA)</strong>।</p>

<blockquote>"এই বিশেষ ইনজেকশনটি মস্তিষ্কের বন্ধ হয়ে যাওয়া রক্তনালীর জমাট রক্তকে জাদুর মতো গলিয়ে দিয়ে রক্তপ্রবাহ পুনরায় চালু করে দেয়। ফলে রোগী কয়েক ঘণ্টার ব্যবধানে পক্ষাঘাত বা প্যারালাইসিস থেকে মুক্ত হয়ে সম্পূর্ণ সুস্থ মানুষের মতো হেঁটে বাড়ি ফিরে যেতে পারেন! কিন্তু সাড়ে চার ঘণ্টা পার হয়ে গেলে এই ইনজেকশন আর কোনো কাজ করে না।"</blockquote>

<h2>স্ট্রোকের ক্ষেত্রে কোন ভুলগুলো কখনোই করবেন না?</h2>
<ul>
  <li><strong>সরিষা বা রসুনের তেল মালিশ করবেন না:</strong> এটি গ্রামীণ কুসংস্কার। মস্তিষ্কের ভেতরের বন্ধ রক্তনালী গায়ের চামড়ায় তেল ডললে কখনোই খুলবে না; এতে কেবল গোল্ডেন আওয়ারের অমূল্য সময় অপচয় হবে।</li>
  <li><strong>রোগীর মুখে জোর করে পানি, দুধ বা ফলের রস দেবেন না:</strong> স্ট্রোক হলে গলার গিলবার স্নায়ু অবশ হয়ে যায়। এই অবস্থায় পানি খাওয়ালে তা খাদ্যনালীতে না গিয়ে সোজা শ্বাসনালী হয়ে ফুসফুসে ঢুকে যায় (Aspiration Pneumonia), ফলে রোগী শ্বাসকষ্টে ছটফট করে মারা যেতে পারেন।</li>
  <li><strong>মাথার চুল কামিয়ে রক্ত বের করা বা সুই ফোটানো সম্পূর্ণ কুসংস্কার:</strong> ফেসবুকের অপপ্রচারে কান দিয়ে রক্তক্ষরণ ঘটাতে যাবেন না।</li>
</ul>

<h2>৮০ শতাংশ স্ট্রোক সম্পূর্ণ প্রতিরোধযোগ্য</h2>
