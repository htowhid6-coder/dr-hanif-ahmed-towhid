<p>হৃদযন্ত্র হলো আমাদের বেঁচে থাকার প্রধান পাম্প। এর মাংসপেশিতে রক্ত সরবরাহের জন্য রয়েছে সরু কিছু নালী, যাকে করোনারি ধমনী বলা হয়। যখন এই রক্তনালীতে রক্ত জমাট বেঁধে রক্তপ্রবাহ বন্ধ হয়ে যায়, তখন হার্টের সেই নির্দিষ্ট অংশের কোষগুলো অক্সিজেনের অভাবে এক এক করে মরতে শুরু করে।</p>

<p>মেডিকেলের ভাষায় একটি আপ্তবাক্য আছে: <strong>"টাইম ইজ মাসল" (Time is Muscle)</strong>। অর্থাৎ যত সময় গড়াবে, হার্টের মাংসপেশির তত বড় অংশ চিরতরে অকেজো বা পচে নষ্ট হয়ে যাবে। হার্ট অ্যাটাকের লক্ষণ শুরু হওয়ার প্রথম <strong>১ থেকে ২ ঘণ্টাকে বলা হয় 'গোল্ডেন আওয়ার' (The Golden Hour)</strong>। এই সময়ের মধ্যে রোগীকে হাসপাতালে পৌঁছাতে পারলে রক্ত পাতলা করার বিশেষ ইনজেকশন (Thrombolytic Therapy) বা এনজিওগ্রাম করে রিং পরিয়ে (Primary PCI) হার্টের মাংসপেশিকে সম্পূর্ণ রক্ষা করা সম্ভব। অথচ ঘরে বসে গ্যাস্ট্রিকের বড়ি খেয়ে সময় নষ্ট করলে হার্ট চিরদিনের জন্য শক্তি হারিয়ে হার্ট ফেইলিওরের দিকে চলে যায়।</p>

