<p class="lead font-medium text-lg text-emerald-950">চেম্বারে একজন মাঝবয়সী ভদ্রলোক এলেন, উনার স্ত্রীকে নিয়ে। রোগীর চেয়ারে বসা আপুকে দেখার পর, প্রেসক্রিপশন লেখার শেষ মুহূর্তে ভাইয়া লাজুক হেসে অনুরোধ করলেন—<em>"স্যার, সময় থাকলে আমার ব্লাড প্রেসারটা একটু চেক করে দিতেন? কয়দিন ধরে মেপে দেখা হয় না।"</em></p>

<p>উনার শার্টের হাতা গুটিয়ে রক্তচাপ মাপার কাফটি বাঁধলাম। স্টেথোস্কোপ কানের পর্দায় লাগিয়ে যখন পারদ স্তম্ভের দিকে তাকালাম, চোখ কপালে ওঠার দশা। রিডিং আসলো ১৮০/১০০ মিলিমিটার অব মার্কারি! ডাক্তারি ভাষায় যাকে আমরা বলি 'স্টেজ-৩ হাইপারটেনশন' (Stage-3 Severe Hypertension)। আমি পুনরায় পরীক্ষা করলাম, কিন্তু কোনো পরিবর্তন নেই। যখন উনাকে অত্যন্ত সতর্কতার সাথে জানালাম যে এই রক্তচাপ মারাত্মক ঝুঁকিপূর্ণ এবং উচ্চ রক্তচাপের নেপথ্য কারণ ও শরীরের ভেতরে কোনো ক্ষতি হয়েছে কি না তা দেখার জন্য জরুরি কিছু রক্ত-প্রস্রাব ও ইসিজি টেস্ট প্রয়োজন, তখন উনি পরম শান্তিতে মুচকি হেসে বললেন—</p>

<p class="text-xl font-serif text-accent font-semibold italic my-4 border-l-4 border-accent pl-4">"স্যার, কিন্তু আমার ত কোনও সমস্যা হচ্ছে না... না মাথা ঘোরে, না বুক ধড়ফড় করে। দিব্যি হেঁটে চলে বেড়াচ্ছি। তাহলে অযথা টেস্ট আর ওষুধের কী দরকার?"</p>

<p>উনার এই আত্মবিশ্বাসী রেসপন্সটি আমার খুব চেনা। শুধু উনার একার নয়—সিলেটসহ আমাদের সারা দেশের অধিকাংশ মানুষেরই এটি সাধারণ ও সার্বজনীন প্রতিক্রিয়া। আমাদের সমাজ ব্যথা ছাড়া রোগ বিশ্বাস করতে চায় না। দাঁত ব্যথা হলে আমরা অস্থির হয়ে ছুটি, পেটে মোচড় দিলে ফার্মেসিতে দৌড়াই; কিন্তু উচ্চ রক্তচাপের মতো চরম সংহারী ব্যাধি যখন শরীরে বাসা বাঁধে, কোনো বাহ্যিক চিৎকার না থাকায় আমরা ধরে নিই শরীর সম্পূর্ণ সুস্থ। সমস্যা যেহেতু আপাতদৃষ্টিতে হচ্ছে না, তাহলে কেন উচ্চ রক্তচাপের ওষুধ খাব? কেনই-বা চিকিৎসকের ফলো-আপে বারবার আসব, অযথা টাকা খরচ করে পরীক্ষা করাব? আজ আমার এই লেখার উদ্দেশ্য ঠিক এই বিপজ্জনক ভ্রান্ত ধারণার শিকড় উপড়ে ফেলা।</p>

<h2>ব্লাড প্রেসার ও প্রমত্তা নদীর উপমা: বিজ্ঞানের সহজ পাঠ</h2>
<p>উচ্চ রক্তচাপকে বুঝতে হলে আমাদের রক্ত সংবহনতন্ত্রকে একটি বিশালাকার নদী বা সেচ ব্যবস্থার সাথে তুলনা করতে হবে। হৃদযন্ত্র হলো একটি শক্তিশালী পাম্প মেশিন, যা সারাদিনে প্রায় ১ লক্ষ বার স্পন্দিত হয়ে সারা শরীরে রক্ত পাঠায়। রক্তনালীগুলো হলো সেই নদীর তটরেখা বা বাঁধ। নদীর জলের স্বাভাবিক প্রবাহে তীর নিরাপদ থাকে। কিন্তু বর্ষার দিনে পাহাড়ি ঢলে যখন জলের তীব্র স্রোত ও বেগ সৃষ্টি হয়, তখন প্রতিটি বাঁকে ও পাড়ে আছড়ে পড়া ধাক্কা নদীর তীরবর্তী মাটিকে ভেতর থেকে আলগা করে দেয়।</p>

<p>আমাদের শরীরের ধমনীগুলোর ক্ষেত্রেও ঠিক এটিই ঘটে। রক্তচাপ ১৮০/১০০ হওয়া মানে হলো—আপনার প্রতিটা হৃৎস্পন্দনে রক্তনালীর মসৃণ অন্তঃপ্রাচীরে (Endothelium) এক ধ্বংসাত্মক মাইক্রো-ধাক্কা লাগছে। নদীর গভীর পাড় যেমন নিঃশব্দে ক্ষয় হতে হতে হঠাৎ কোনো পূর্বাভাস ছাড়াই হুড়মুড় করে তলিয়ে যায়, মানবদেহের রক্তনালীও দিনের পর দিন উচ্চ রক্তচাপের ধাক্কা সহ্য করতে করতে একসময় ফেটে যায়।</p>

<h2>মস্তিষ্কে রক্তক্ষরণ: হেমোরেজিক স্ট্রোকের নির্মম বাস্তবতা</h2>
<p>আমাদের মস্তিষ্কের রক্তনালীগুলো অত্যন্ত সূক্ষ্ম, নরম ও সর্পিল। ক্রনিক হাইপারটেনশনের মুখে মস্তিষ্কের ক্ষুদ্রাতিক্ষুদ্র রক্তনালীগুলোতে ছোট ছোট বেলুনের মতো ফোসকা তৈরি হয় (যাকে চিকিৎসা বিজ্ঞানে Charcot-Bouchard microaneurysms বলা হয়)। কোনো একদিন অতিরিক্ত মানসিক চাপ, একটু ভারী কাজ বা কোনো স্পষ্ট কারণ ছাড়াই রক্তের তীব্র স্রোতে এই ফোসকা ফেটে যায়। মস্তিষ্কের নরম কোষগুলোতে রক্ত ছড়িয়ে পড়ে—যাকে আমরা বলি <strong>হেমোরেজিক স্ট্রোক (Hemorrhagic Stroke)</strong>।</p>

<p>কয়েক মিনিটের ব্যবধানে একজন সুস্থ, কর্মক্ষম মানুষ চিরদিনের জন্য ডান পাশ বা বাম পাশ অবশ হয়ে বিছানায় পড়ে যান, বাকশক্তি হারিয়ে ফেলেন, কিংবা কোমায় চলে গিয়ে মৃত্যুর কোলে ঢলে পড়েন। হাসপাতালে নিয়ে আসার পর যখন স্বজনরা কাঁদেন আর বলেন—"ডাক্তার সাহেব, কাল রাতেও তো ভালো ছিলেন, হঠাৎ কী হলো?", তখন উত্তর দেওয়ার ভাষা চিকিৎসকদের থাকে না। কারণ ক্ষতিটা এক রাতে হয়নি; ক্ষতিটা হয়েছে বিগত ৫-১০ বছর ধরে নীরবে ১৮০ প্রেসার পুষে রাখার কারণে!</p>

<h2>শরীরের অন্যান্য অঙ্গে অদৃশ্য ধ্বংসযজ্ঞ</h2>
<p>উচ্চ রক্তচাপ কেবল মাথায় আঘাত করে না; এটি শরীরের প্রধান প্রধান গুরুত্বপূর্ণ অঙ্গগুলোকে ভেতর থেকে নিঃশেষ করে দেয়:</p>
<ul>
  <li><strong>হৃৎপিণ্ডের দেয়াল পুরু হওয়া ও হার্ট ফেইলিওর (Left Ventricular Hypertrophy):</strong> অতিরিক্ত বাধার বিরুদ্ধে রক্ত পাম্প করতে করতে হার্টের পেশি অস্বাভাবিক ভারী ও শক্ত হয়ে যায়। ফলে হৃদযন্ত্রের রক্ত গ্রহণের ক্ষমতা নষ্ট হয় এবং রোগী অল্পতেই হাঁপিয়ে ওঠেন, পায়ে পানি জমে।</li>
  <li><strong>কিডনির ছাঁকনি ধ্বংস (Renal Failure):</strong> কিডনি কোটি কোটি আণুবীক্ষণিক ফিল্টারের (Nephrons) সাহায্যে রক্ত পরিষ্কার করে। উচ্চ রক্তচাপ এই নাজুক ফিল্টারগুলোকে পুড়িয়ে ঝাঁঝরা করে ফেলে। বাংলাদেশে ডায়ালাইসিস গ্রহণকারী কিডনি রোগীদের একটি বিশাল অংশ এই অবহেলিত উচ্চ রক্তচাপের শিকার।</li>
  <li><strong>চোখের রেটিনার ক্ষতি (Hypertensive Retinopathy):</strong> চোখের পেছনের দৃষ্টিপর্দার রক্তনালী ছিঁড়ে গিয়ে দৃষ্টিশক্তি ধীরে ধীরে অন্ধত্বের দিকে চলে যায়।</li>
</ul>

<blockquote>"উচ্চ রক্তচাপের সবচেয়ে বড় চাতুর্য হলো—এটি যখন ভেতরে ভেতরে আপনার হার্ট, কিডনি ও ব্রেনকে ধসিয়ে দেয়, তখনো বাইরে থেকে আপনি হয়তো একবিন্দু শারীরিক কষ্ট অনুভব করবেন না। আর এই কারণেই চিকিৎসা বিজ্ঞানে একে বলা হয়েছে 'নীরব ঘাতক' (The Silent Killer)।"</blockquote>

