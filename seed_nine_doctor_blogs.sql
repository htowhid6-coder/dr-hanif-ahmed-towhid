  <li><strong>ডায়াবেটিক নেফ্রোপ্যাথি (কিডনি বিকল):</strong> কিডনির ছাঁকনি দিয়ে প্রোটিন বা অ্যালবুমিন লিক হতে থাকে। কোনো লক্ষণ ছাড়া চলতে চলতে একসময় রোগী সরাসরি ডায়ালাইসিসের মুখোমুখি হন।</li>
  <li><strong>ডায়াবেটিক নিউরোপ্যাথি (স্নায়ু অবশ হওয়া):</strong> পায়ের স্নায়ুগুলো অনুভূতিহীন হয়ে যায়। ফলে জুতোয় ঘষা লাগলে, পেরেকের গুঁতো খেলে কিংবা আগুনে ছ্যাঁকা লাগলেও রোগী কোনো ব্যথা পান না। সেই সামান্য ক্ষত থেকেই তৈরি হয় ভয়ানক ডায়াবেটিক ফুট আলসার ও গ্যাংগ্রিন, যা থেকে শেষ পর্যন্ত পা কেটে বাদ দিতে হয়।</li>
  <li><strong>সাইলেন্ট হার্ট অ্যাটাক:</strong> ডায়াবেটিস রোগীদের হার্টের ব্যথার স্নায়ুগুলো ক্ষতিগ্রস্ত হওয়ার কারণে হার্ট অ্যাটাক হলেও বুকে কোনো তীব্র ব্যথা হয় না; কেবল একটু হাঁপিয়ে ওঠা বা ক্লান্তি লাগে!</li>
  <li><strong>পুরুষের যৌন অক্ষমতা ও প্রজনন সমস্যা:</strong> পেনাইল আর্টারির রক্তপ্রবাহ ক্ষতিগ্রস্ত হয়ে ইরেকটাইল ডিসফাংশন দেখা দেয়।</li>
