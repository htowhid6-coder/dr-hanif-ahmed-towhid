<h2>লক্ষণহীন ডায়াবেটিসের গোলকধাঁধা: ৫০% রোগী কিছুই টের পান না!</h2>
<p>আমাদের দেশের মানুষের ডায়াবেটিস নিয়ে সবচেয়ে বড় ভুল ধারণা হলো পাঠ্যপুস্তকের সেই প্রাচীন লক্ষণের জন্য অপেক্ষা করা—পলিইউরিয়া (ঘন ঘন প্রস্রাব), পলিডিপসিয়া (অতিরিক্ত পিপাসা), আর পলিফেজিয়া (অস্বাভাবিক ক্ষুধা)। কিন্তু সমসাময়িক ক্লিনিক্যাল এপিডেমিওলজির নির্মম সত্য হলো:</p>

<blockquote>"টাইপ-২ ডায়াবেটিসে আক্রান্ত মোট প্রাপ্তবয়স্ক রোগীদের প্রায় ৫০ থেকে ৬০ শতাংশই রোগের প্রাথমিক ৫ থেকে ৭ বছর কোনো বাহ্যিক কষ্ট বা উপসর্গ একবিন্দুও টের পান না!"</blockquote>

<p>কেন এমন হয়? কারণ আমাদের শরীর এক অবিশ্বাস্য সহনশীল কারখানা। রক্তে সুগার যখন স্বাভাবিকের চেয়ে একটু একটু করে বাড়তে থাকে (যেমন ৭ থেকে ১০ বা ১২ মিলিমোল), কিডনি তখনো সেই সুগারকে সামলে নেওয়ার চেষ্টা করে। যতক্ষণ না পর্যন্ত রক্তের সুগার ১০ বা ১১ মিলিমোল অতিক্রম করে প্রস্রাবে উপচে পড়ে (Renal Threshold for Glucose), ততক্ষণ ঘন ঘন প্রস্রাব হয় না। আর এই নীরব বছরগুলোতে উচ্চ গ্লুকোজযুক্ত রক্ত ধীরগতির বিষের মতো শরীরের ভেতরের সূক্ষ্ম রক্তনালীগুলোকে পুড়িয়ে ঝাঁঝরা করে ফেলে।</p>

<h2>প্যাথোফিজিওলজির সহজ পাঠ: তালা-চাবির অকেজো খেলা</h2>
<p>টাইপ-২ ডায়াবেটিসে আসলে কী ঘটে? আমাদের অগ্ন্যাশয় বা প্যানক্রিয়াস পর্যাপ্ত ইনসুলিন হরমোন তৈরি করে। ইনসুলিনের কাজ হলো রক্তে ঘুরে বেড়ানো খাদ্য-উৎপন্ন গ্লুকোজকে শরীরের মাংসপেশি ও লিভারের কোষের ভেতরে ঢুকিয়ে দেওয়া, যাতে কোষগুলো শক্তি পায়। কোষের দরজায় থাকে একটি বিশেষ তালা (Insulin Receptor), আর ইনসুলিন হলো সেই তালার চাবি।</p>

<p>কিন্তু যখন কোনো ব্যক্তি অতিরিক্ত শারীরিক নিষ্ক্রিয়তায় ভোগেন, তলপেটে চর্বি জমান, অতিরিক্ত ভাত-মিষ্টি খান এবং মানসিক চাপে থাকেন, তখন কোষের সেই তালাগুলোতে চর্বির জং ধরে যায়! একে চিকিৎসা বিজ্ঞানে বলা হয় <strong>ইনসুলিন রেজিস্ট্যান্স (Insulin Resistance)</strong>। চাবি থাকা সত্ত্বেও তালা খোলে না। ফলে গ্লুকোজ কোষের ভেতরে ঢুকতে না পেরে রক্তস্রোতেই জমতে থাকে। প্যানক্রিয়াস তখন দ্বিগুণ শক্তিতে ইনসুলিন তৈরি করতে থাকে। একপর্যায়ে অগ্ন্যাশয়ের বিটা কোষগুলো ক্লান্ত হয়ে হাঁপিয়ে ওঠে এবং রক্তে সুগার স্থায়ীভাবে মারাত্মক পর্যায়ে চলে যায়।</p>

<h2>নীরব ডায়াবেটিসের ৫টি অদৃশ্য ধ্বংসযজ্ঞ</h2>
