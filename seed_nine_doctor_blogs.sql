<h2>কোলেস্টেরল আসলে কী: বিষ নাকি জীবনের মৌলিক উপাদান?</h2>
<p>প্রথমেই একটি চমকপ্রদ বৈজ্ঞানিক সত্য জানা দরকার—কোলেস্টেরল কিন্তু কোনো অপ্রয়োজনীয় বিষাক্ত উপাদান নয়। এটি একটি মোমজাতীয় চর্বি (Lipid), যা ছাড়া মানুষ এক মুহূর্তও বেঁচে থাকতে পারবে না। আমাদের শরীরের প্রতিটি কোষের বহিরাবরণী তৈরি করতে, সূর্যের আলো থেকে ত্বকে ভিটামিন-ডি সংশ্লেষণ করতে, খাবার হজমের পিত্তরস (Bile Acid) বানাতে এবং টেস্টোস্টেরন বা ইস্ট্রোজেনের মতো অতি গুরুত্বপূর্ণ হরমোন উৎপাদনে কোলেস্টেরল অপরিহার্য।</p>

<p>মজার ব্যাপার হলো—আমাদের রক্তের মোট কোলেস্টেরলের প্রায় ৭৫ থেকে ৮০ শতাংশই তৈরি করে আমাদের <strong>লিভার (যকৃত)</strong> নিজে! খাবার থেকে আসে মাত্র ২০ থেকে ২৫ শতাংশ। তাহলে সমস্যা কোথায়? সমস্যা হলো যখন এই চর্বি বহনকারী কণাগুলোর মধ্যে ভারসাম্যহীনতা দেখা দেয়। রক্তের লিপিড প্যানেলে মূলত তিনটি প্রধান উপাদান দেখা হয়:</p>
<ul>
  <li><strong>এলডিএল (LDL - Low-Density Lipoprotein):</strong> একে বলা হয় "খারাপ কোলেস্টেরল"। এটি লিভার থেকে চর্বি নিয়ে রক্তনালীর দেওয়ালে জমা করে এবং রক্তনালী সরু করে ফেলে (Atherosclerosis)।</li>
  <li><strong>এইচডিএল (HDL - High-Density Lipoprotein):</strong> এটি হলো আমাদের পরম বন্ধু বা "ভালো কোলেস্টেরল"। এটি রক্তনালীর দেওয়াল থেকে অতিরিক্ত চর্বি কুড়িয়ে নিয়ে পুনরায় লিভারে ফেরত পাঠায় ধ্বংস করার জন্য।</li>
  <li><strong>ট্রাইগ্লিসারাইড (Triglycerides):</strong> এটি মূলত আমরা যে অতিরিক্ত ক্যালোরি, চিনি, ভাত বা মিষ্টি খাই, তা থেকে তৈরি হওয়া জমা চর্বি।</li>
</ul>

